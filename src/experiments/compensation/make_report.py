MATHS = r"""\section{The models and the maths}
\subsection{Pinhole projection}
A point $\mathbf{X}_w$ on the board is moved into the camera frame by the board pose $(R_k,\mathbf{t}_k)$,
$\mathbf{X} = R_k\mathbf{X}_w + \mathbf{t}_k = (X, Y, Z)$, and projected to normalised coordinates
$x = X/Z,\; y = Y/Z$. A lens model maps $(x,y)$ to distorted coordinates $(x_d, y_d)$ and the camera matrix
\[ K=\begin{pmatrix} f_x & 0 & c_x\\ 0 & f_y & c_y\\ 0&0&1\end{pmatrix},\qquad u = f_x x_d + c_x,\quad v = f_y y_d + c_y \]
gives the pixel. Every model below except T5 sends all rays through one point, the camera centre: it is a
\emph{single-viewpoint} (central) camera.

\subsection{T3: Brown-Conrady}
With $r^2 = x^2 + y^2$,
\[ x_d = x(1 + k_1 r^2 + k_2 r^4 + k_3 r^6) + 2p_1xy + p_2(r^2 + 2x^2),\quad
   y_d = y(1 + k_1 r^2 + k_2 r^4 + k_3 r^6) + p_1(r^2 + 2y^2) + 2p_2xy. \]
Nine intrinsics: $f_x, f_y, c_x, c_y, k_1, k_2, p_1, p_2, k_3$. Fitted with \texttt{cv2.calibrateCamera}
(Zhang's closed-form start from the board homographies, then Levenberg-Marquardt).

\subsection{T4: Kannala-Brandt}
The distortion acts on the ray angle $\theta = \arctan r$ instead of on $r$:
\[ \theta_d = \theta\,(1 + k_1\theta^2 + k_2\theta^4 + k_3\theta^6 + k_4\theta^8),\qquad
   (x_d, y_d) = \frac{\theta_d}{r}(x, y). \]
Eight intrinsics. Fitted with \texttt{cv2.fisheye.calibrate}. Its stereo extrinsics are fitted by the same
pixel-error least squares as \texttt{cv2.stereoCalibrate} (\texttt{models.stereo\_lm}), because OpenCV 5.0.0's fisheye stereo
calibration cannot take pairs with different numbers of points.

\subsection{T1: in-air calibration, unchanged}
The Brown-Conrady calibration made in air (the same rig, same detector) is used underwater as it is,
including its stereo extrinsics. Near the axis a flat interface multiplies the focal length by the water's
refractive index, $f_\text{water}\approx n\,f_\text{air}$ with $n\approx1.33$, so T1 is expected to fail badly;
it is the floor that every compensation method has to beat.

\subsection{T2: Pinax (in-air calibration + refraction)}
Following Łuczyński, Pfingsthorn and Birk (2017), a pixel is undistorted with the in-air model to its air-side
ray $(x_a, y_a, 1)$ at angle $\theta_a = \arctan r_a$, and Snell's law at the port,
\[ \sin\theta_a = n \sin\theta_w \quad\Rightarrow\quad r_w = \tan\!\left(\arcsin\frac{\sin(\arctan r_a)}{n}\right), \]
gives the water-side ray $(x_w, y_w) = (x_a, y_a)\,r_w/r_a$. The glass index cancels out of the direction.
Projection runs the chain backwards. The rays are taken from Pinax's single virtual centre on the axis; its
offset (set by lens-to-port distance and port thickness, which have no physical value for a water-contact
lens) is a constant shift that each board pose absorbs. No intrinsic is fitted in water; the stereo
extrinsics are fitted on the underwater pairs. Fresh water, $n = 1.333$, is assumed; the water type was not
recorded.

\subsection{T5: Brown-Conrady + axial shift (non-single-viewpoint)}
Behind a refracting port the rays of different field angles cross the optical axis at different points.
For a port centred on the axis the spread is symmetric, so a ray is fully described by its Brown-Conrady
direction $(x, y, 1)$ and where it crosses the axis:
\[ \mathbf{o}(r) = \bigl(0,\,0,\,\Delta z(r)\bigr),\qquad \Delta z(r) = a_1 r^2 + a_2 r^4\ \text{(mm)},\quad r = \sqrt{x^2+y^2}. \]
A constant term would only move the camera centre, which the board poses absorb. With $a_1 = a_2 = 0$ this
\emph{is} T3, so the two are nested: if T5 does not improve held-out error, the data are consistent with a
single viewpoint. A point $(X,Y,Z)$ lies on the ray through $(x,y)$ when $(X,Y) = (Z - \Delta z(r))(x,y)$, so
projection solves
\[ r\,\bigl(Z - \Delta z(r)\bigr) = \sqrt{X^2+Y^2} \]
for $r$ by Newton's method from the pinhole value $r = \sqrt{X^2+Y^2}/Z$, then distorts as T3. The shift
moves a pixel by about $f\,r\,\Delta z / Z$: it changes with distance, which is what separates it from radial
distortion, so it can only be measured from boards at several distances. T5 is fitted by bundle adjustment
(\texttt{scipy.optimize.least\_squares}, pixel error) over the 11 intrinsics and every board pose, started
from T3's fit with $\Delta z = 0$.

\subsection{Scoring on held-out recordings}
Each recording is one sweep of the board from about 0.25 to 1.4~m at one tilt, and its frames are near
duplicates, so whole recordings are held out: every choice of 2 of the 8 recordings (28 splits). A technique
is fitted on the other 6 and each held-out image is then posed with the intrinsics fixed, minimising pixel
error, and reprojected. With residuals $\mathbf{e}_i = \mathbf{u}_i - \hat{\mathbf{u}}_i$,
\[ \text{RMS} = \sqrt{\tfrac{1}{N}\textstyle\sum_i \lVert\mathbf{e}_i\rVert^2}. \]
Because each held-out board gets its own fitted pose (6 parameters), part of any model error is absorbed: the
held-out RMS is a lower bound. The triangulated lengths below use no board pose, so they do not have this bias.
Every metric has one value per split; tables give the mean and the 2.5--97.5 percentile range over the 28
splits. Two techniques are compared \emph{paired} (same split, same frames): a difference is ``within noise''
when the range of the per-split difference contains 0.

The image is split into zones by the radius from the principal point, normalised so the farthest image corner
is 1: centre $r<0.33$, mid $<0.66$, outer beyond. Near is boards at 200--800~mm, far 1000--1500~mm.

\subsection{Stereo scale}
Held-out stereo pairs are triangulated with the technique's two cameras and its stereo extrinsics (fitted on
the training pairs with the intrinsics fixed; T1 keeps the in-air ones). Central models use
\texttt{cv2.triangulatePoints} on the normalised rays; T5 uses the midpoint of the shortest segment between the
two rays, each leaving from its own axis crossing (the two agree to $10^{-6}$~mm for central models). Every
pair of corners 250--450~mm apart on the board is a scale bar: its triangulated length minus its true length is
the length error. Each stereo pair is summarised by its mean and RMS bar error.

\subsection{The WaterComparison target}
A separate target, six AprilTag 36h11 tags (ids 6--11, 3 rows $\times$ 2 columns) printed with a 145~mm outer
square, was recorded once at each distance label 50, 100, 150, 200 and 250~cm. The tags are detected once
(the \texttt{water\_final} preset on CLAHE-enhanced gray, 1-bit border, OpenCV's contour corner refinement;
the pipeline's \texttt{cornerSubPix} window, tuned to the calibration board's X-junctions, moves these
corners by up to 26~px), and the same pixels are triangulated by every technique, each fitted on all 8
recordings. A tag's error is its median edge length minus 145~mm, so one misplaced corner (two bad edges)
does not decide it. The calibration boards reached about 1.4~m, so the 150--250~cm labels test extrapolation.

\subsection{Parameter covariance and correlation}
A calibration is a least-squares fit of intrinsics $\mathbf{p}$ ($m$ of them) and one pose $\mathbf{q}_k$ per
image. With independent pixel noise of variance $\sigma^2$, the covariance of the estimates is
$\sigma^2(J^\top J)^{-1}$, $J$ being the Jacobian of the residuals. The intrinsics' block of that inverse is the
inverse of the Schur complement
\[ A = \sum_k \Bigl[ J_{p,k}^\top J_{p,k} - J_{p,k}^\top J_{q,k}\,\bigl(J_{q,k}^\top J_{q,k}\bigr)^{-1} J_{q,k}^\top J_{p,k}\Bigr],
   \qquad \Sigma_p = \hat\sigma^2 A^{-1},\quad \hat\sigma^2 = \frac{\sum_i\lVert\mathbf{e}_i\rVert^2}{2N - m - 6F}, \]
which accounts for every pose being estimated at the same time. This is the estimate OpenCV's
\texttt{calibrateCameraExtended} reports (the implementation reproduces it to $10^{-5}$ for Brown-Conrady,
checked in the tests). The correlation $C_{ij} = \Sigma_{ij}/(\sigma_i\sigma_j)$ shows which parameters the
data cannot tell apart: $|C_{ij}|$ near 1 means a change in one is almost exactly undone by the other. It is a
statement about the fit, not about accuracy: the held-out tests above measure accuracy.
"""


