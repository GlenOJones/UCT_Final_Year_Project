def project_path(path):
    return path if os.path.isabs(path) else os.path.join(PROJECT_ROOT, path)


def load_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def load_run(out_dir):
    with open(os.path.join(out_dir, "summary.csv"), newline="") as fh:
        summary = {(r["technique"], r["camera"], r["metric"]): r for r in csv.DictReader(fh)}
    with open(os.path.join(out_dir, "comparisons.csv"), newline="") as fh:
        comparisons = {(r["a"], r["b"], r["camera"], r["metric"]): r for r in csv.DictReader(fh)}
    info = load_json(os.path.join(out_dir, "run_info.json"))
    params = {t["key"]: load_json(os.path.join(out_dir, "params", f"{t['key']}.json")) for t in info["config"]["techniques"]}
    optional = {name: load_json(os.path.join(out_dir, f"{name}.json")) if os.path.exists(os.path.join(out_dir, f"{name}.json")) else None
                for name in ("target", "covariance")}
    return summary, comparisons, info, params, optional["target"], optional["covariance"]


# ====== LATEX HELPERS ======
def tex(s):
    """Escape plain text for LaTeX."""
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def num(x, digits=3):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    return "--" if v != v else f"{v:.{digits}f}"


def interval(row, digits=3):
    """'mean [lo, hi]' from a summary.csv row, as LaTeX."""
    if row is None or row["mean"] in ("", "nan"):
        return "--"
    return f"{num(row['mean'], digits)} {{\\scriptsize[{num(row['lo'], digits)}, {num(row['hi'], digits)}]}}"


def figure(out_dir, name, caption, width=r"\linewidth", place="H"):
    path = os.path.join(out_dir, f"{name}.pdf")
    if not os.path.exists(path):
        return f"% {name}.pdf not produced by this run\n"
    return (f"\\begin{{figure}}[{place}]\\centering\n\\includegraphics[width={width},height=0.85\\textheight,keepaspectratio]{{../{name}.pdf}}\n"
            f"\\caption{{{caption}}}\\label{{fig:{name}}}\n\\end{{figure}}\n")


def table(caption, label, header, rows, align=None, size=r"\small"):
    align = align or "l" + "r" * (len(header) - 1)
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (f"\\begin{{table}}[H]\\centering{size}\n\\caption{{{caption}}}\\label{{tab:{label}}}\n"
            f"\\resizebox{{\\linewidth}}{{!}}{{%\n\\begin{{tabular}}{{{align}}}\n\\toprule\n"
            f"{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}}}\n\\end{{table}}\n")


