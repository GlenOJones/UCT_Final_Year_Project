def build(tex_path):
    folder = os.path.dirname(tex_path)
    if not shutil.which("pdflatex"):
        print("pdflatex not found: wrote the .tex only")
        return None
    for _ in range(2):
        proc = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", os.path.basename(tex_path)],
                              cwd=folder, capture_output=True, text=True)
        if proc.returncode:
            sys.stdout.write(proc.stdout[-3000:])
            raise SystemExit(f"pdflatex failed on {tex_path}")
    return tex_path[:-4] + ".pdf"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=CONFIG_FILE, help="the comparison config (default config_full.json here)")
    ap.add_argument("--out", help="the run's output folder (default: the config's 'output')")
    args = ap.parse_args(argv)
    cfg = load_json(args.config)
    out_dir = project_path(args.out or cfg["output"])
    summary, comparisons, info, params, target, cov = load_run(out_dir)
    techs = info["config"]["techniques"]
    CAMERAS[:] = cfg.get("report_cameras", CAMERAS)

    doc = "\n".join([
        PREAMBLE, r"\begin{document}", r"\maketitle", r"\tableofcontents", r"\newpage",
        section_overview(info, techs), MATHS,
        section_running(info, os.path.relpath(os.path.abspath(args.config), PROJECT_ROOT).replace("_", r"_")),
        section_results(out_dir, summary, comparisons, info, params, target, cov, techs),
        section_discussion(info, project_path(cfg.get("report", {}).get("discussion", DISCUSSION))),
        r"\end{document}", ""])
    report_dir = os.path.join(out_dir, "report")
    os.makedirs(report_dir, exist_ok=True)
    tex_path = os.path.join(report_dir, "methods_report.tex")
    with open(tex_path, "w", encoding="utf-8") as fh:
        fh.write(doc)
    pdf = build(tex_path)
    print(f"wrote {os.path.relpath(tex_path, PROJECT_ROOT)}" + (f" and {os.path.relpath(pdf, PROJECT_ROOT)}" if pdf else ""))


if __name__ == "__main__":
    main()
