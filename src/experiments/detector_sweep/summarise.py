"""Compare the detector presets from their calibrations: what each detects and how well it then fits.

Reads the Calibration.py runs reproduce.py made for config.json "presets" (one per medium and preset, same
channel and calibration settings), so the preset is the only thing that differs. Nothing is detected here.

Per medium and preset:
    tags            distinct board tags per image, summed over both cameras' images (what the sweep maximises)
    usable          images with at least min_tags distinct board tags
    bad rate        false ids + duplicate ids, as a share of all detections
    kept            images left after outlier rejection, left / right
    RMS common      RMS of the per-image errors over only the images every preset's run kept, left / right:
                    the like-for-like fit quality (see compare_calibrations.py for why headline RMS is not)
    stereo RMS      and the pairs it was fitted on

Use (from the project root; reproduce.py detector_sweep makes the calibrations and runs this):
    src/venv/bin/python src/experiments/detector_sweep/summarise.py
Writes <out_dir>/presets/summary.{json,md}.
"""
import argparse
import json
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import common  # noqa: E402
from common import Calibration as C  # noqa: E402
from compare_calibrations import read_run, rms  # noqa: E402  (src/01_Calibration, on the path via common)

CONFIG_FILE = os.path.join(HERE, "config.json")


def preset_runs(cfg):
    """{medium: {preset: YAML path}} of the preset comparison calibrations."""
    out_dir = common.project_path(cfg["out_dir"])
    runs = {}
    for medium, frames in cfg["media"].items():
        for preset in cfg["presets"]["names"]:
            settings = {**cfg["calibration"], "preset": preset, "channel": cfg["presets"]["channel"]}
            yaml_path, _ = common.calibration_paths(settings, common.project_path(frames),
                                                    os.path.join(out_dir, "calibration", medium))
            runs.setdefault(medium, {})[preset] = yaml_path
    return runs


def detection_counts(path, min_tags):
    """Tags, usable images, bad detections and image count from the YAML's detection section."""
    fs = cv2.FileStorage(path, cv2.FILE_STORAGE_READ)
    seq = lambda n: [int(n.at(i).real()) for i in range(n.size())]  # noqa: E731
    tags = usable = false = duplicates = images = 0
    for camera in C.CAMERAS:
        node = fs.getNode("detection").getNode(camera)
        found = seq(node.getNode("tags_found"))
        tags += sum(found)
        usable += sum(n >= min_tags for n in found)
        false += sum(seq(node.getNode("false_found")))
        duplicates += sum(seq(node.getNode("duplicate_found")))
        images += len(found)
    stereo = fs.getNode("stereo")
    total = tags + false + duplicates
    return {"tags": tags, "usable": usable, "images": images, "bad": false + duplicates,
            "bad_rate": (false + duplicates) / total if total else 0.0,
            "stereo_rms_px": stereo.getNode("rms_reprojection_error_px").real(),
            "stereo_pairs": int(stereo.getNode("pairs_used").real())}


def summarise(cfg):
    min_tags = cfg["calibration"]["min_tags"]
    summary = {}
    for medium, paths in preset_runs(cfg).items():
        runs = {p: read_run(path) for p, path in paths.items()}
        missing = [common.rel(paths[p]) for p, r in runs.items() if r is None]
        if missing:
            raise SystemExit(f"missing {', '.join(missing)}: run reproduce.py detector_sweep first")
        common_images = {cam: set.intersection(*(set(r["cameras"][cam]["per_image"]) for r in runs.values()))
                         for cam in C.CAMERAS}
        summary[medium] = {"common_images": {cam: len(v) for cam, v in common_images.items()}, "presets": {}}
        for preset, run in runs.items():
            row = detection_counts(paths[preset], min_tags)
            for cam in C.CAMERAS:
                per_image = run["cameras"][cam]["per_image"]
                row[f"kept_{cam}"] = run["cameras"][cam]["n_images"]
                row[f"rms_{cam}_px"] = run["cameras"][cam]["rms"]
                row[f"rms_common_{cam}_px"] = rms([per_image[n] for n in common_images[cam]])
            row["yaml"] = common.rel(paths[preset])
            summary[medium]["presets"][preset] = row
    return summary


def markdown(summary, cfg):
    lines = ["# Detector presets compared", "",
             f"Generated by src/experiments/detector_sweep/summarise.py. Channel {cfg['presets']['channel']}, "
             f"outlier rejection {'on' if cfg['calibration']['reject'] else 'off'}, usable = at least "
             f"{cfg['calibration']['min_tags']} tags. RMS common: over the images every preset's run kept.", ""]
    for medium, m in summary.items():
        lines += [f"## {medium} (common set: {m['common_images']['left']} left, {m['common_images']['right']} right images)", "",
                  "| preset | tags | usable / images | bad rate | kept L / R | RMS common L / R px | stereo RMS px (pairs) |",
                  "|---|---|---|---|---|---|---|"]
        for preset, r in m["presets"].items():
            lines.append(f"| {preset} | {r['tags']} | {r['usable']} / {r['images']} | {100 * r['bad_rate']:.2f} % | "
                         f"{r['kept_left']} / {r['kept_right']} | {r['rms_common_left_px']:.3f} / {r['rms_common_right_px']:.3f} | "
                         f"{r['stereo_rms_px']:.3f} ({r['stereo_pairs']}) |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=CONFIG_FILE, help="experiment config (default config.json here)")
    cfg = common.load_config(ap.parse_args(argv).config)
    summary = summarise(cfg)
    out = os.path.join(common.project_path(cfg["out_dir"]), "presets")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "summary.json"), "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=1)
    text = markdown(summary, cfg)
    with open(os.path.join(out, "summary.md"), "w", encoding="utf-8") as fh:
        fh.write(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
